"""Failure-mode traces -> CSVs in models/out and Resilient fixtures in software/resilient.

    python3 electrode_model.py stress     # ~1 min; regenerates both

The traces use the tissue-grade membrane (gox_pu_tissue, linear to 30 mM at tissue O2),
72 h at 5 min, 512 kohm gain. The calibration is the fresh sensor's noise-free response at
40 and 400 mg/dL, as a bench two-point calibration would record it.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

import electrode_model as em

MGDL_PER_MM = 18.0156
RZ_PATH = Path(__file__).resolve().parents[1] / "software" / "resilient" / "stress_fixtures.rz"


def fresh_calibration_pa(result: dict, low_mgdl=40, high_mgdl=400) -> tuple[int, int]:
    c = result["_curves"]
    return tuple(int(round(float(np.interp(g / MGDL_PER_MM, c["conc"], c["tissue"])) * 1000)) for g in (low_mgdl, high_mgdl))


def rz_array(name: str, values, comment: str) -> str:
    body = ", ".join(str(int(v)) for v in values)
    return f"// {comment}\nfn {name}() -> array {{\n    return [{body}];\n}}\n\n"


def write_outputs(traces: dict[str, np.ndarray], result: dict, out_dir: Path, rz_path: Path = RZ_PATH):
    for name, tr in traces.items():
        np.savetxt(out_dir / f"synthetic_trace_{name}.csv", tr, delimiter=",", fmt="%.4f",
                   header="t_s,blood_glucose_mM,isf_glucose_mM,raw_current_nA", comments="")
    first = next(iter(traces.values()))
    n = len(first)
    low_pa, high_pa = fresh_calibration_pa(result)
    parts = [
        "// GENERATED by `python3 models/electrode_model.py stress` from models/stress_fixtures.py. Do not edit.\n"
        "// Synthetic traces from the 1D electrode model for failure modes; invented, not measured.\n"
        f"// {n} samples at {int(em.STRESS_DT_S)} s ({em.STRESS_HOURS:.0f} h), currents in pA, glucose in mg/dL.\n\n"
        "use \"calibration_guard.rz\";\n\n"
        f"fn stress_samples() -> int {{ return {n}; }}\n"
        f"fn stress_step_ms() -> int {{ return {int(em.STRESS_DT_S * 1000)}; }}\n\n"
        "fn stress_calibration() -> Calibration {\n"
        "    return new Calibration {\n"
        "        enabled: true,\n        id: 1,\n"
        f"        low_current_pa: {low_pa},\n        high_current_pa: {high_pa},\n"
        "        low_glucose_mgdl: 40,\n        high_glucose_mgdl: 400,\n"
        "        min_temp_mc: 35000,\n        max_temp_mc: 39000,\n    };\n}\n\n"
        "fn stress_policy() -> GuardPolicy {\n"
        "    return new GuardPolicy {\n"
        "        max_calibration_age_ms: 345600000,\n"
        "        min_sensitivity_permille: 850,\n        max_sensitivity_permille: 1150,\n"
        "        max_rate_mgdl_per_min_x10: 40,\n        rate_window_ms: 900000,\n    };\n}\n\n"
    ]
    parts.append(rz_array("stress_blood_mgdl", np.round(first[:, 1] * MGDL_PER_MM), "fingerstick reference (blood glucose)"))
    parts.append(rz_array("stress_isf_mgdl", np.round(first[:, 2] * MGDL_PER_MM), "interstitial glucose the sensor should read"))
    for name, tr in traces.items():
        f = em.STRESS_VARIANTS[name]
        parts.append(rz_array(f"{name}_current_pa", np.round(tr[:, 3] * 1000), f"{name}: {f if f else 'only the default 5 %/day sensitivity drift'}"))
    rz_path.write_text("".join(parts))
